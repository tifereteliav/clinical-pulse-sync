// ניקוד: תשובה נכונה = 500 עד 1000 נקודות לפי מהירות
export function calcPoints(correct, elapsedMs, timeSec) {
  if (!correct) return 0;
  const ratio = Math.min(1, Math.max(0, elapsedMs / (timeSec * 1000)));
  return Math.round(1000 - 500 * ratio);
}

